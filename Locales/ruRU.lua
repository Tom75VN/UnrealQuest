-- The standard Russian rule: ONE for 1, 21, 31 ... (but not 11),
-- FEW for 2-4, 22-24 ... (but not 12-14), MANY for the rest.
--
-- The % operator rather than math.mod: Core/Namespace.lua's quest-colour
-- hash already runs % on this client, where math.mod is a Lua 5.0 spelling
-- with no runtime record here.
UQ.RegisterLocalePlural("ruRU", function(n)
    local hundreds = n % 100
    if hundreds >= 11 and hundreds <= 14 then
        return "MANY"
    end
    local tens = n % 10
    if tens == 1 then
        return "ONE"
    end
    if tens >= 2 and tens <= 4 then
        return "FEW"
    end
    return "MANY"
end)
