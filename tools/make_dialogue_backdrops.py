"""Build the quest dialogue's per-zone portrait backdrops and their index.

Sources: media/Textures/Dialogues/Portrait_Background/<Zone>.<ext>
         (.png, .jpg, .jpeg, .webp, .bmp; or a ready .tga)
Output:  the same folder, <Zone>.tga for every non-TGA source, and
         Data/DialogueBackdrops.lua (UQ.dialogueBackdrops: area ID -> <Zone>).

<Zone> is the zone's English name with everything but letters and digits
dropped, in any case: "Elwynn Forest" -> ElwynnForest, "Stranglethorn Vale"
-> StranglethornVale, "The Barrens" -> TheBarrens. A trailing area ID is
accepted for runtime files (361_Felwood.tga). A name several areas carry
(Westfall is area 40 and area 206) maps all of them. A bare area ID
(1581.png) names exactly that area. Names are matched against
Database/enUS/zones.lua, so a dungeon or a city works the same way.

A non-TGA source is cropped to the portrait hole's aspect
(QUEST_DIALOGUE_LAYOUTS["horde-light"].hole), resized to 256x256 and written as
32-bit RLE TGA, exactly like make_dialogue_horde_light.py's UQ_Portrait_Background_Wide.
A source that is already .tga is kept as delivered and only its header and
size are checked. The index is rebuilt from what is in the folder every run,
so a removed image drops out of it.

Run from the addon root:  python tools/make_dialogue_backdrops.py
"""

import os
import re
import sys

from PIL import Image

ROOT = os.getcwd()
FOLDER = os.path.join(ROOT, "media", "Textures", "Dialogues", "Portrait_Background")
ZONES = os.path.join(ROOT, "Database", "enUS", "zones.lua")
INDEX = os.path.join(ROOT, "Data", "DialogueBackdrops.lua")

SOURCE_EXTENSIONS = (".png", ".jpg", ".jpeg", ".webp", ".bmp")
SIZE = 256
# Width over height of the portrait hole (QUEST_DIALOGUE_LAYOUTS["horde-light"].hole).
PORTRAIT_HOLE_ASPECT = 164.5 / 150.2


def key(name):
    return re.sub(r"[^a-z0-9]", "", name.lower())


def load_zone_names():
    names = {}
    pattern = re.compile(r'^\s*\[(\d+)\]\s*=\s*"((?:[^"\\]|\\.)*)"')
    with open(ZONES, encoding="utf-8") as handle:
        for line in handle:
            match = pattern.match(line)
            if match:
                names[int(match.group(1))] = match.group(2)
    return names


def check_tga(path):
    with open(path, "rb") as handle:
        header = handle.read(18)
    if len(header) != 18 or header[2] not in (2, 10) or header[16] not in (24, 32):
        return "not a 24/32-bit truecolor TGA"
    width = header[12] | (header[13] << 8)
    height = header[14] | (header[15] << 8)
    if width & (width - 1) or height & (height - 1) or max(width, height) > 512:
        return "size %dx%d is not a power of two up to 512" % (width, height)
    return None


def write_tga(source, target):
    image = Image.open(source).convert("RGB")
    width, height = image.size
    if float(width) / height > PORTRAIT_HOLE_ASPECT:
        cropped = int(round(height * PORTRAIT_HOLE_ASPECT))
        box = ((width - cropped) // 2, 0, (width - cropped) // 2 + cropped, height)
    else:
        cropped = int(round(width / PORTRAIT_HOLE_ASPECT))
        box = (0, (height - cropped) // 2, width, (height - cropped) // 2 + cropped)
    image = image.crop(box).resize((SIZE, SIZE), Image.LANCZOS).convert("RGBA")
    image.save(target, format="TGA", compression="tga_rle")
    with open(target, "rb") as handle:
        header = handle.read(18)
    if len(header) != 18 or header[2] != 10 or header[16] != 32 or header[17] != 8:
        sys.exit("unexpected TGA header written for %s" % target)


def lua_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_index(entries, names):
    lines = [
        "--[[",
        "UnrealQuest / Data/DialogueBackdrops.lua",
        "",
        "The quest dialogue's portrait backdrop per zone, one set shared by every",
        "theme:",
        "area ID to the file name under",
        "media/Textures/Dialogues/Portrait_Background/. A texture path",
        "cannot be tested for existence on this client",
        "(textures.gettexture_echoes_missing_path), so only an area listed here",
        "gets its own backdrop; every other area keeps the theme's default.",
        "",
        "Generated by tools/make_dialogue_backdrops.py from the images in that",
        "folder. Regenerate rather than hand-edit.",
        "]]",
        "",
        "local UQ = UnrealQuest",
        "",
        "UQ.dialogueBackdrops = {",
    ]
    for area_id in sorted(entries):
        lines.append("    [%d] = %s, -- %s" % (area_id, lua_string(entries[area_id]),
                                               names.get(area_id, "?")))
    lines.append("}")
    with open(INDEX, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")


def main():
    if not os.path.isdir(FOLDER):
        os.makedirs(FOLDER)
    names = load_zone_names()
    by_key = {}
    for area_id, name in names.items():
        by_key.setdefault(key(name), []).append(area_id)

    stems = {}
    for filename in sorted(os.listdir(FOLDER)):
        stem, extension = os.path.splitext(filename)
        extension = extension.lower()
        if extension == ".tga" or extension in SOURCE_EXTENSIONS:
            stems.setdefault(stem, []).append(extension)

    entries = {}
    problems = []
    for stem in sorted(stems):
        if re.search(r"[^A-Za-z0-9_]", stem):
            problems.append("%s: use letters, digits and _ only in the file name" % stem)
            continue
        lookup_stem = stem
        explicit_area = None
        match = re.match(r"^(\d+)_(.*)$", stem)
        if match:
            explicit_area = int(match.group(1))
            lookup_stem = match.group(2)
        if lookup_stem.isdigit():
            areas = [int(lookup_stem)] if int(lookup_stem) in names else []
        else:
            areas = by_key.get(key(lookup_stem), [])
        if explicit_area is not None and explicit_area not in areas:
            problems.append("%s: area %d does not match this zone name"
                            % (stem, explicit_area))
            continue
        if not areas:
            problems.append("%s: no zone in Database/enUS/zones.lua has this name" % stem)
            continue
        sources = [e for e in stems[stem] if e != ".tga"]
        target = os.path.join(FOLDER, stem + ".tga")
        if sources:
            write_tga(os.path.join(FOLDER, stem + sources[0]), target)
        else:
            problem = check_tga(target)
            if problem:
                problems.append("%s.tga: %s" % (stem, problem))
                continue
        for area_id in areas:
            if area_id in entries and entries[area_id] != stem:
                problems.append("area %d is named by both %s and %s"
                                % (area_id, entries[area_id], stem))
                continue
            entries[area_id] = stem
        print("  %-28s -> %s" % (stem, ", ".join("%d %s" % (a, names[a]) for a in sorted(areas))))

    write_index(entries, names)
    print("wrote %s (%d areas)" % (os.path.relpath(INDEX, ROOT), len(entries)))
    if problems:
        print("skipped:")
        for problem in problems:
            print("  " + problem)
        sys.exit(1)


if __name__ == "__main__":
    main()
